import data from '../data/laluan.json';
import {dayIndex,myDay} from './daily';

/* Laluan Masa: draw one line through every cell, joining textbook events in chronological order.
   Events and puzzles are generated by scripts/build-laluan.mjs from data/chronology/kronologi.txt. */
export type ChronoEvent={id:string;f:number;b:number;p:number;d:string;l:string};
export type Puzzle={n:number;scope:string;cp:number[];ev:string[];tag:string};
export type DailyPuzzle=Puzzle&{number:number;index:number;events:ChronoEvent[]};

export const PENALTY_MS=10000;
const events=data.events as ChronoEvent[];
const puzzles=data.puzzles as Puzzle[];
const byId=new Map(events.map(e=>[e.id,e]));
export const eventCount=events.length;

/** Index into the puzzle cycle for a Malaysia date ('YYYY-MM-DD'); matches private.chrono_day_index. */
export function puzzleIndex(day:string=myDay()):number{
 const n=puzzles.length;return ((dayIndex(data.epoch,day)%n)+n)%n;
}

/** The puzzle for a day. `number` counts days since launch (puzzle #1 = epoch). */
export function puzzleFor(day:string=myDay(),index:number=puzzleIndex(day)):DailyPuzzle{
 const p=puzzles[index];
 return {...p,index,number:dayIndex(data.epoch,day)+1,events:p.ev.map(id=>byId.get(id)!)};
}

export const adjacent=(n:number,a:number,b:number)=>Math.abs(a%n-b%n)+Math.abs(Math.floor(a/n)-Math.floor(b/n))===1;

/** Same rule as private.chrono_path_ok on the server. */
export function pathSolves(n:number,cp:number[],path:number[]):boolean{
 if(path.length!==n*n||new Set(path).size!==n*n||path.some(c=>c<0||c>=n*n))return false;
 for(let i=1;i<path.length;i++)if(!adjacent(n,path[i-1],path[i]))return false;
 const hits=path.filter(c=>cp.includes(c));
 return hits.length===cp.length&&hits.every((c,i)=>c===cp[i])&&path[0]===cp[0]&&path[path.length-1]===cp[cp.length-1];
}

export type Step={kind:'add'|'back'|'start'}|{kind:'wrong';checkpoint:number}|{kind:'blocked';reason:'start'|'finish'|'far'|'visited'};

/** What happens when the line tries to move onto `cell`. Wrong checkpoints count as mistakes. */
export function tryStep(n:number,cp:number[],path:number[],cell:number):Step{
 const cpAt=cp.indexOf(cell);
 if(!path.length){
  if(cell===cp[0])return {kind:'start'};
  return cpAt>0?{kind:'wrong',checkpoint:cpAt}:{kind:'blocked',reason:'start'};
 }
 const last=path[path.length-1];
 if(path.length>1&&cell===path[path.length-2])return {kind:'back'};
 if(cell===last)return {kind:'blocked',reason:'visited'};
 if(!adjacent(n,last,cell))return {kind:'blocked',reason:'far'};
 if(path.includes(cell))return {kind:'blocked',reason:'visited'};
 if(last===cp[cp.length-1])return {kind:'blocked',reason:'finish'};
 if(cpAt>=0){
  const next=path.filter(c=>cp.includes(c)).length;
  if(cpAt!==next)return {kind:'wrong',checkpoint:cpAt};
  if(cpAt===cp.length-1&&path.length+1<n*n)return {kind:'blocked',reason:'finish'};
 }
 return {kind:'add'};
}

const MONTHS=['Januari','Februari','Mac','April','Mei','Jun','Julai','Ogos','September','Oktober','November','Disember'];
const MONTHS_EN=['January','February','March','April','May','June','July','August','September','October','November','December'];
/** '1914-07-28' -> '28 Julai 1914'; '1945-09' -> 'September 1945'; '1957' -> '1957'. */
export function formatEventDate(d:string,en=false):string{
 const [y,m,day]=d.split('-');const names=en?MONTHS_EN:MONTHS;
 if(!m)return y;const month=names[Number(m)-1];
 return day?(en?`${month} ${Number(day)}, ${y}`:`${Number(day)} ${month} ${y}`):`${month} ${y}`;
}

export function formatTime(ms:number):string{
 const s=Math.max(0,ms)/1000;const m=Math.floor(s/60);const rest=s-m*60;
 return `${m}:${rest.toFixed(1).padStart(4,'0')}`;
}
